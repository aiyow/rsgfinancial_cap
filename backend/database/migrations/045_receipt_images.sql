BEGIN;

ALTER TABLE payment_submissions
  ADD COLUMN IF NOT EXISTS receipt_type VARCHAR(20) NOT NULL DEFAULT 'OTHER',
  ADD COLUMN IF NOT EXISTS ocr_details JSONB NOT NULL DEFAULT '{}'::jsonb;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'payment_submissions_receipt_type_check') THEN
    ALTER TABLE payment_submissions ADD CONSTRAINT payment_submissions_receipt_type_check
      CHECK (receipt_type IN ('GCASH','GOTYME','MARIBANK','BDO','BPI','MAYA','OTHER'));
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS payment_receipt_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_submission_id BIGINT NOT NULL REFERENCES payment_submissions(id) ON DELETE CASCADE,
  position SMALLINT NOT NULL CHECK (position IN (1,2)),
  storage VARCHAR(20) NOT NULL,
  path TEXT NOT NULL,
  cloudinary_public_id TEXT,
  original_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(50) NOT NULL CHECK (mime_type IN ('image/jpeg','image/png')),
  sha256 CHAR(64) NOT NULL,
  ocr_analysis JSONB NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT payment_receipt_images_position_unique UNIQUE (payment_submission_id, position),
  CONSTRAINT payment_receipt_images_sha256_unique UNIQUE (sha256),
  CONSTRAINT payment_receipt_images_storage_check CHECK (
    (storage = 'LOCAL' AND cloudinary_public_id IS NULL)
    OR (storage = 'CLOUDINARY' AND cloudinary_public_id IS NOT NULL))
);

INSERT INTO payment_receipt_images
  (payment_submission_id,position,storage,path,cloudinary_public_id,original_name,mime_type,sha256)
SELECT id,1,receipt_storage,receipt_path,receipt_cloudinary_public_id,receipt_original_name,receipt_mime_type,receipt_sha256
FROM payment_submissions WHERE entry_type = 'RECEIPT_UPLOAD'
ON CONFLICT (payment_submission_id,position) DO NOTHING;

COMMIT;
