import assert from 'node:assert/strict';
import test from 'node:test';
import express from 'express';
import jwt from 'jsonwebtoken';
import ExcelJS from 'exceljs';
import pool from '../../config/db.js';
import importRoutes from '../../routes/analyticsImportRoutes.js';
import errorHandler from '../../middleware/errorHandler.js';
import { workbookFilename, workbookMimeType } from '../../services/analyticsWorkbook.js';

test('history downloads export legacy readings and retain confirmed original workbooks atomically', async () => {
  const client = await pool.connect(), query = client.query.bind(client);
  const originalQuery = pool.query, originalConnect = pool.connect, originalSecret = process.env.JWT_SECRET;
  let server, failArchive = false, sequence = 0;
  const savepoints = [];
  try {
    await query('BEGIN');
    await query(`
      CREATE TEMP TABLE users (id BIGINT PRIMARY KEY, role TEXT, is_active BOOLEAN, auth_version INT DEFAULT 0) ON COMMIT DROP;
      CREATE TEMP TABLE units (id BIGINT PRIMARY KEY, unit_number TEXT) ON COMMIT DROP;
      CREATE TEMP TABLE billing_periods (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        period_start DATE UNIQUE,period_end DATE,due_date DATE,water_rate_per_cubic_m NUMERIC,
        association_dues_rate_per_sqm NUMERIC,status TEXT,created_by BIGINT,period_type TEXT,readings_visible_at TIMESTAMPTZ) ON COMMIT DROP;
      CREATE TEMP TABLE meter_readings (id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,unit_id BIGINT,billing_period_id BIGINT,
        recorded_by BIGINT,previous_reading NUMERIC,current_reading NUMERIC,validation_status TEXT,validation_notes TEXT) ON COMMIT DROP;
      CREATE TEMP TABLE billing_forecasts (id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,unit_id BIGINT,based_on_period_id BIGINT,
        forecast_for_month DATE,predicted_consumption NUMERIC,estimated_water_charge NUMERIC,model_name TEXT,sample_count INT,
        slope NUMERIC,intercept NUMERIC,forecast_status TEXT,status_reason TEXT) ON COMMIT DROP;
      CREATE TEMP TABLE analytics_import_workbooks (billing_period_id BIGINT PRIMARY KEY REFERENCES billing_periods(id) ON DELETE CASCADE,
        original_name TEXT,workbook_data BYTEA,uploaded_by BIGINT,uploaded_at TIMESTAMPTZ DEFAULT NOW()) ON COMMIT DROP;
      CREATE TEMP TABLE prescriptive_recommendations (LIKE public.prescriptive_recommendations INCLUDING DEFAULTS) ON COMMIT DROP;
      INSERT INTO users(id,role,is_active) VALUES (1,'COLLECTOR',TRUE),(2,'RESIDENT',TRUE),(3,'ADMIN',TRUE);
      INSERT INTO units VALUES(1,'101'),(2,'102');
      INSERT INTO billing_periods(id,period_start,period_end,due_date,water_rate_per_cubic_m,period_type,status,readings_visible_at)
        VALUES(100,'2026-01-01','2026-01-31','2026-01-31',23,'HISTORICAL_ANALYTICS','CLOSED',NOW()),
              (200,'2026-10-05','2026-10-31','2026-10-31',23,'LIVE_BILLING','DRAFT',NULL);
      INSERT INTO meter_readings(unit_id,billing_period_id,previous_reading,current_reading,validation_status)
        VALUES(1,100,100,110,'VALID'),(2,100,200,200,'VALID'),(1,200,110,120,'VALID'),(2,200,200,205,'VALID');
    `);
    async function routeQuery(sql, values) {
      if(sql==='BEGIN') {const name=`history_${++sequence}`;savepoints.push(name);return query(`SAVEPOINT ${name}`);}
      if(sql==='COMMIT') return query(`RELEASE SAVEPOINT ${savepoints.pop()}`);
      if(sql==='ROLLBACK') {const name=savepoints.pop();await query(`ROLLBACK TO SAVEPOINT ${name}`);return query(`RELEASE SAVEPOINT ${name}`);}
      if(failArchive&&sql.includes('INSERT INTO analytics_import_workbooks')) throw Object.assign(new Error('Simulated archive failure'),{status:503});
      return query(sql,values);
    }
    pool.query=routeQuery;pool.connect=async()=>({query:routeQuery,release(){}});
    process.env.JWT_SECRET='isolated-history-download-test';
    const token=id=>jwt.sign({id,authVersion:0},process.env.JWT_SECRET);
    const app=express();app.use(express.json());app.use('/api/analytics/imports',importRoutes);app.use(errorHandler);
    server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
    const base=`http://127.0.0.1:${server.address().port}/api/analytics/imports`;
    const request=(path='',options={})=>fetch(base+path,{...options,headers:{Authorization:`Bearer ${token(1)}`,...options.headers}});
    assert.equal((await fetch(base+'/2026-01/workbook')).status,401);
    for(const id of [2,3]) assert.equal((await request('/2026-01/workbook',{headers:{Authorization:`Bearer ${token(id)}`}})).status,403);
    assert.equal((await request('/2026-13/workbook')).status,400);
    assert.equal((await request('/2026-12/workbook')).status,404);
    assert.equal((await request('/2026-10/workbook')).status,404,'Live billing must not be treated as a historical import');
    const legacy=await request('/2026-01/workbook');
    assert.equal(legacy.status,200);
    assert(legacy.headers.get('content-type').includes(workbookMimeType));
    assert(legacy.headers.get('content-disposition').includes('water-history-2026-01.xlsx'));
    assert.equal(legacy.headers.get('cache-control'),'private, no-store');
    const legacyWorkbook=new ExcelJS.Workbook();await legacyWorkbook.xlsx.load(Buffer.from(await legacy.arrayBuffer()));
    assert.deepEqual(legacyWorkbook.worksheets[0].getRow(1).values.slice(1,7),['UNIT','PREVIOUS','PRESENT','CONSUMPTION','WRATE','WATER BILLED']);
    assert.equal(legacyWorkbook.worksheets[0].getCell('D2').value,10);
    assert.equal(legacyWorkbook.worksheets[0].getCell('F2').value,230);
    assert.equal(legacyWorkbook.worksheets[0].getCell('D3').value,0);
    assert.equal(legacyWorkbook.worksheets[0].getCell('F3').value,0);
    assert(legacyWorkbook.getWorksheet('About this export'));
    const original=new ExcelJS.Workbook(), sheet=original.addWorksheet('Original source');
    sheet.addRows([['UNIT','PREVIOUS','PRESENT','CONSUMPTION','WRATE','WATER BILLED'],['101',110,120,10,23,230],['102',200,205,5,23,115]]);
    original.addWorksheet('Extra information').getCell('A1').value='Original formatting and extra sheets must be retained.';
    const bytes=Buffer.from(await original.xlsx.writeBuffer());
    const upload=(buffer=bytes,periodMonth='2026-02')=>{
      const form=new FormData();form.append('periodMonth',periodMonth);form.append('file',new Blob([buffer],{type:workbookMimeType}),'February original.xlsx');
      return request('',{method:'POST',body:form});
    };
    const livePreviewForm=new FormData();livePreviewForm.append('periodMonth','2026-10');livePreviewForm.append('file',new Blob([bytes],{type:workbookMimeType}),'October.xlsx');
    const livePreview=await request('/preview',{method:'POST',body:livePreviewForm});
    assert.equal((await livePreview.json()).usesExistingLiveBilling,true,'A batch starting on the 5th belongs to the selected calendar month');
    const liveVerified=await upload(bytes,'2026-10');
    assert.equal(liveVerified.status,200);
    assert.equal((await liveVerified.json()).reusedLiveBilling,true);
    assert.equal((await query("SELECT COUNT(*)::int AS count FROM billing_periods WHERE DATE_TRUNC('month',period_start)='2026-10-01'")).rows[0].count,1,'Verifying a live month must not duplicate its analytics');
    failArchive=true;
    assert.equal((await upload()).status,503);
    failArchive=false;
    assert.equal((await query("SELECT COUNT(*)::int AS count FROM billing_periods WHERE period_start='2026-02-01'")).rows[0].count,0,'Failed archive rolls back imported readings');
    const imported=await upload();assert.equal(imported.status,201,await imported.text());
    const list=await (await request()).json();
    assert.equal(list.imports.find(row=>row.periodMonth==='2026-02').originalFilename,'February original.xlsx');
    const downloaded=await request('/2026-02/workbook');
    assert.equal(downloaded.status,200);
    assert(downloaded.headers.get('content-disposition').includes('February original.xlsx'));
    assert.deepEqual(Buffer.from(await downloaded.arrayBuffer()),bytes,'Original workbook bytes and extra worksheets must be unchanged');
    const replacement=await request('',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({periodMonth:'2026-02',waterRatePerCubicM:23,
      readings:[{unitId:1,previousReading:110,currentReading:121},{unitId:2,previousReading:200,currentReading:205}]})});
    assert.equal(replacement.status,201,await replacement.text());
    assert.equal((await query('SELECT COUNT(*)::int AS count FROM analytics_import_workbooks')).rows[0].count,0,'A JSON replacement must not serve an outdated original');
    const exported=new ExcelJS.Workbook();await exported.xlsx.load(Buffer.from(await (await request('/2026-02/workbook')).arrayBuffer()));
    assert.equal(exported.worksheets[0].getCell('C2').value,121);
    assert.equal((await upload()).status,201);
    const deleted=await request('/2026-02',{method:'DELETE'});assert.equal(deleted.status,200,await deleted.text());
    assert.equal((await query('SELECT COUNT(*)::int AS count FROM analytics_import_workbooks')).rows[0].count,0,'Deleting the import cascades to its retained file');
    assert.equal((await request('/2026-02/workbook')).status,404);
    const invalid=new ExcelJS.Workbook();invalid.addWorksheet('Missing columns').addRow(['UNIT']);
    assert.equal((await upload(Buffer.from(await invalid.xlsx.writeBuffer()))).status,400);
    assert.equal(workbookFilename('C:\\fakepath\\original.xlsx','2026-01'),'original.xlsx');
    assert.equal(workbookFilename('wrong.pdf','2026-01'),'water-history-2026-01.xlsx');
  } finally {
    if(server) await new Promise(resolve=>server.close(resolve));
    pool.query=originalQuery;pool.connect=originalConnect;
    if(originalSecret===undefined) delete process.env.JWT_SECRET;else process.env.JWT_SECRET=originalSecret;
    await query('ROLLBACK');client.release();await pool.end();
  }
});
